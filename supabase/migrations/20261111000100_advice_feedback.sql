BEGIN;
-- Post-advice feedback: each participant may rate an advice connection once.
-- Participant and request-status rules are enforced by the Flask API.
CREATE TABLE IF NOT EXISTS public.advice_feedback (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_id bigint NOT NULL REFERENCES public.advice_requests(id),
 rater_id bigint NOT NULL REFERENCES public.students(id),
 rating smallint NOT NULL CHECK (rating BETWEEN 1 AND 10),
 helpful boolean NOT NULL,
 comment text NOT NULL DEFAULT '' CHECK (length(comment) <= 500),
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE (request_id, rater_id)
);
CREATE INDEX IF NOT EXISTS feedback_by_rater ON public.advice_feedback (rater_id);
ALTER TABLE public.advice_feedback ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.advice_feedback FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.advice_feedback TO service_role;
DO $$ DECLARE seq text := pg_get_serial_sequence('public.advice_feedback', 'id'); BEGIN
 EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC, anon, authenticated', seq);
 EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO service_role', seq);
END $$;
NOTIFY pgrst, 'reload schema';
COMMIT;
